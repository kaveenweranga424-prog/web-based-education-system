package model;

public class TutorProfile {

    private int tutorProfileId;
    private int userId;
    private String firstName; // joined
    private String lastName;  // joined
    private String email;     // joined
    private String phone;     // joined
    private String specialization;
    private String bio;
    private String status;

    public TutorProfile() {
    }

    public int getTutorProfileId() {
        return tutorProfileId;
    }

    public void setTutorProfileId(int tutorProfileId) {
        this.tutorProfileId = tutorProfileId;
    }

    public int getUserId() {
        return userId;
    }

    public void setUserId(int userId) {
        this.userId = userId;
    }

    public String getFirstName() {
        return firstName;
    }

    public void setFirstName(String firstName) {
        this.firstName = firstName;
    }

    public String getLastName() {
        return lastName;
    }

    public void setLastName(String lastName) {
        this.lastName = lastName;
    }

    public String getFullName() {
        return firstName + " " + lastName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getSpecialization() {
        return specialization;
    }

    public void setSpecialization(String specialization) {
        this.specialization = specialization;
    }

    public String getBio() {
        return bio;
    }

    public void setBio(String bio) {
        this.bio = bio;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }
}